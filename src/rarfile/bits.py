RAR_BLOCK_OLD_AUTH: Final = 0x79       #: RAR2 authenticity
RAR_BLOCK_SUB: Final = 0x7a            #: RAR3 named subblock
RAR_BLOCK_ENDARC: Final = 0x7b         #: End of archive

