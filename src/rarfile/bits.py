from typing import Final

# block types: 'r'..'{'
RAR_BLOCK_MARK: Final = 0x72           #: Archive signature
RAR_BLOCK_MAIN: Final = 0x73           #: Archive header
RAR_BLOCK_FILE: Final = 0x74           #: File entry
