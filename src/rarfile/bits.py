# Host OS types
RAR_OS_MSDOS: Final = 0    #: MSDOS (only in RAR3)
RAR_OS_OS2: Final = 1      #: OS2 (only in RAR3)
RAR_OS_WIN32: Final = 2    #: Windows
RAR_OS_UNIX: Final = 3     #: UNIX
RAR_OS_MACOS: Final = 4    #: MacOS (only in RAR3)
RAR_OS_BEOS: Final = 5     #: BeOS (only in RAR3)

# Compression methods - "0".."5"
RAR_M0: Final = 0x30   #: No compression.
RAR_M1: Final = 0x31   #: Compression level `-m1` - Fastest compression.
RAR_M2: Final = 0x32   #: Compression level `-m2`.
RAR_M3: Final = 0x33   #: Compression level `-m3`.
RAR_M4: Final = 0x34   #: Compression level `-m4`.
RAR_M5: Final = 0x35   #: Compression level `-m5` - Maximum compression.

RAR_MAX_PASSWORD: Final = 127  # Max number of utf-16 chars in passwords.
RAR_MAX_KDF_SHIFT: Final = 24  # Max power-of-2 for KDF count
RAR_MAX_COMMENT: Final = 256 * 1024  # Max supported comment size

